class Solution{
    public long countCommas(long n){
        if(n<=999)return 0;
        else if(n<1000000L)return n-999L;
        else if(n<1000000000L)return (999999L-999L)+(n-999999L)*2;
        else if(n<1000000000000L)return (999999L-999L)+(999999999L-999999L)*2+(n-999999999L)*3;
        else if(n<1000000000000000L)return (999999L-999L)+(999999999L-999999L)*2+(999999999999L-999999999L)*3
 +(n-999999999999L)*4;

        return (999999L-999L) +(999999999L-999999L)*2 +(999999999999L-999999999L)*3 +(999999999999999L-999999999999L)*4 +(n-999999999999999L)*5;
    }
}